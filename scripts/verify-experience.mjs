import assert from 'node:assert/strict';
import { parseObservations, quickEstimate, observedRisk, recordNotice } from '../src/lib/observations.js';
import { simulate, DEFAULT_SETTINGS, parseClock } from '../src/lib/simulate.js';
assert.equal(parseObservations('').values.length,0);
for(const text of ['0,40,50','3,4,no','4,5','30,Infinity,40','30,40,361'])assert(parseObservations(text).error);
assert.deepEqual(parseObservations('30，40\n50;60').values,[30,40,50,60]);
assert(parseObservations(Array(301).fill(30).join(',')).error);
assert.deepEqual(quickEstimate(40),{min:32,mode:40,max:72});
assert(Number.isNaN(parseClock('09:99'))); assert(Number.isNaN(parseClock('25:00')));
const option={id:'a',name:'实测路线',min:1,mode:2,max:3,cost:6,observations:[40,45,50]};
const result=simulate([option],DEFAULT_SETTINGS,{months:100});
const metric=result.options[0];
assert.equal(metric.daily.quantiles[0],40); assert.equal(metric.daily.quantiles[1000],50);
assert.equal(metric.monthly.cost,264); assert.equal(metric.suggestedDeparture,520);
assert(metric.lateProbAtSuggested<=.05);
const risk=observedRisk([40,45,50],60); assert.equal(risk.late,0); assert(risk.upper>.5);
assert(recordNotice(3,.05).includes('不足'));
const same=simulate([{...option,observations:[42,42,42]}],DEFAULT_SETTINGS,{months:10}).options[0];
assert.equal(same.daily.mean,42); assert.equal(same.daily.spread,0);
assert(same.daily.histogram.counts.every(Number.isFinite));
console.log('Experience checks passed: parser, bounded input, empirical sampling, zero-event uncertainty, constant observations and clock validation. No external calls.');
